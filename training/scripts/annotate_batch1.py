def main():
    # Read unique template_groups
    with open(UTF8_TEMP, 'r', encoding='utf-8') as f:
        content = f.read()
    lines = [l for l in content.split('\n') if l.strip()]
    reader = csv.DictReader(io.StringIO('\n'.join(lines)))
    groups = OrderedDict()
    for row in reader:
        tg = row['template_group']
        if tg not in groups:
            groups[tg] = row['text']

    items = list(groups.items())
    batch_items = items[START_IDX:END_IDX]

    # Check coverage
    annotated_tg = set(ANNOTATIONS.keys())
    batch_tg = set(tg for tg, _ in batch_items)
    missing = batch_tg - annotated_tg
    extra = annotated_tg - batch_tg

    print(f"Batch {BATCH_NUM}: {len(batch_items)} template_groups")
    print(f"Annotated: {len(annotated_tg)}")
    print(f"Missing: {len(missing)}")
    if missing:
        print(f"Missing TGs: {list(missing)[:10]}...")
    print(f"Extra (not in batch): {len(extra)}")
    if extra:
        print(f"Extra TGs: {list(extra)[:10]}...")

    # Save
    out_path = os.path.join(OUT_DIR, f"annotations_batch{BATCH_NUM}.json")
    with open(out_path, 'w', encoding='utf-8') as f:
        json.dump(ANNOTATIONS, f, ensure_ascii=False, indent=2)
    print(f"Saved to {out_path}")

if __name__ == '__main__':
    main()
